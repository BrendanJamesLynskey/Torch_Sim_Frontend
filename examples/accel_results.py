"""Every number quoted about the accelerator model (simfront.accel) in the README, docs and deck SimEng 14.

    python examples/accel_results.py             # writes examples/accel_results.md and docs/img/*.png

About 3 minutes on a 2012 four-core desktop; the benchmark section dominates. Accelerator
parameters are the illustrative presets in src/simfront/accel/hw.py. Every timing in §7 is
the best of several runs on this machine and will differ on another.
"""

from __future__ import annotations

import logging
import platform
import subprocess
import tempfile
import time
import warnings
from pathlib import Path

import onnx
import simpy
import torch

from simfront import models
from simfront.accel import ep, fastpath, fifo, lower, preset, report, simulate
from simfront.accel.cycle import simulate_cycles
from simfront.accel.hw import KiB, MiB
from simfront.accel.ntt import polymul_trace
from simfront.accel.plot import timeline_png
from simfront.capture import export_onnx, trace_export, trace_onnx
from simfront.cli import capture as capture_registry

warnings.filterwarnings("ignore")
logging.disable(logging.WARNING)
HERE = Path(__file__).parent
ROOT = HERE.parent
IMG = ROOT / "docs" / "img"
OUT: list[str] = []


def h(title):
    OUT.append(f"\n## {title}\n")


def p(text=""):
    OUT.append(text)


def table(head, rows):
    OUT.append("| " + " | ".join(head) + " |")
    OUT.append("|" + "---|" * len(head))
    for r in rows:
        OUT.append("| " + " | ".join(str(x) for x in r) + " |")
    OUT.append("")


def pct(x):
    return f"{x:.1%}"


def us(x):
    return f"{x * 1e6:,.2f}"


def ms(x):
    return f"{x * 1e3:,.3f}"


def best(fn, n=3):
    out, t = None, float("inf")
    for _ in range(n):
        t0 = time.perf_counter()
        out = fn()
        t = min(t, time.perf_counter() - t0)
    return out, t


def _fp_attr(name):
    from simfront.accel import _fastpath

    return str(getattr(_fastpath, name, "?"))


def cpu_name():
    try:
        for line in Path("/proc/cpuinfo").read_text().splitlines():
            if line.startswith("model name"):
                return line.split(":", 1)[1].strip()
    except OSError:
        pass
    return platform.processor()


def cnn_traces():
    m = models.tiny_cnn()
    ex = trace_export(m, (models.image(),), model_name="tiny-cnn")
    d = tempfile.mkdtemp()
    path = Path(d) / "cnn.onnx"
    ins, params = export_onnx(m, (models.image(),), path)
    on = trace_onnx(path, ins, params, model_name="tiny-cnn")
    return ex, on, path, ins


def stall_cols(rep):
    return [pct(rep.stalls[k] / rep.makespan) for k in ("compute", "load bandwidth", "buffer full", "dependency")]


def main():
    IMG.mkdir(parents=True, exist_ok=True)
    gxx = subprocess.run(["g++", "--version"], capture_output=True, text=True).stdout.splitlines()[0]
    OUT.append("# simfront.accel: results\n")
    OUT.append("Generated by `examples/accel_results.py`; do not edit. Accelerator parameters are the illustrative "
               "presets in `src/simfront/accel/hw.py`.")

    h("1. Environment")
    table(["Item", "Value"], [["CPU", cpu_name()], ["Python", platform.python_version()], ["SimPy", simpy.__version__],
                              ["PyTorch", torch.__version__], ["onnx", onnx.__version__],
                              ["pybind11 (built with)", _fp_attr("pybind11_version")],
                              ["C++ standard (__cplusplus)", _fp_attr("cplusplus")], ["C++ compiler", gxx],
                              ["C++ fast path built", "yes" if fastpath.available() else "no"]])
    cfgs = [preset("edge-npu"), preset("dc-npu")]
    table(["Preset", "Array", "Peak (TFLOP/s)", "Vector lanes", "Buffer", "DRAM (GB/s, channels)", "NoC (GB/s)"],
          [[c.name, f"{c.array_rows}x{c.array_cols}", f"{2 * c.peak_macs / 1e12:,.1f}", c.vector_lanes,
            f"{c.buffer_bytes // MiB} MiB", f"{c.dram_bw / 1e9:,.1f} x{c.dram_channels}", f"{c.noc_bw / 1e9:,.0f}"]
           for c in cfgs])

    # ── 2. FIFO ─────────────────────────────────────────────────────────
    h("2. A bounded FIFO: back-pressure and Little's law")
    p("A producer and a consumer joined by `simpy.Store(capacity=depth)`, 2,000 items, service times uniform in "
      "mean x (1 ± 0.5). *Slow consumer*: producer mean 1.0, consumer mean 1.2. *Bursty*: both mean 1.0, the "
      "producer emits bursts of 8. L is the time-averaged depth; λW is throughput x mean time in the FIFO.")
    rows = []
    runs = {}
    for label, kw in (("slow consumer", {"produce": 1.0, "consume": 1.2}),
                      ("bursty", {"produce": 1.0, "consume": 1.0, "burst": 8})):
        for depth in (1, 2, 4, 8, 16):
            r = fifo.run(depth, **kw)
            runs[(label, depth)] = r
            rows.append([label, depth, f"{r.throughput:.4f}", pct(r.producer_blocked / r.end),
                         pct(r.consumer_starved / r.end), f"{r.mean_depth:.3f}", f"{r.throughput * r.mean_wait:.3f}",
                         r.max_depth])
    table(["Case", "Depth", "Throughput (items/unit)", "Producer blocked", "Consumer starved", "L", "λW", "Max depth"],
          rows)
    _fifo_plot(runs)
    p("![FIFO depth over time](../docs/img/fifo_depth.png)")

    # ── 3. CNN ──────────────────────────────────────────────────────────
    h("3. A convolution network through the accelerator, from torch.export and from ONNX")
    ex, on, onnx_path, onnx_ins = cnn_traces()
    rows = []
    for tr in (ex, on):
        prog = lower(tr, preset("edge-npu"))
        tm, st = simulate(prog)
        rep = report(prog, tm)
        rows.append([tr.route, len(tr.ops), len(prog.ops), prog.n_tiles, f"{sum(t.macs for t in prog.tiles):,}",
                     us(rep.makespan), pct(rep.components["compute array"]["busy"]),
                     pct(rep.components["compute array"]["pe_eff"]), pct(rep.components["off-chip memory"]["bw_util"]),
                     rep.hotspot])
        if tr.route == "export":
            cnn_rep, cnn_prog, cnn_tm = rep, prog, tm
    table(["Route", "Trace operators", "Simulated operators", "Tiles", "Array MACs", "Latency (µs)", "Array busy",
           "PE efficiency", "DRAM bandwidth used", "Hot-spot"], rows)
    p("The full report for the torch.export route (`simfront-accel --model tiny-cnn`):\n")
    p(cnn_rep.to_markdown(6))
    p()
    timeline_png(cnn_prog, cnn_tm, cnn_rep, IMG / "timeline_cnn.png")
    p("![CNN timeline](../docs/img/timeline_cnn.png)")
    h_ = cnn_rep.op_latency_histogram(6)
    p("\nOperator latency histogram (log bins):\n")
    table(["From (µs)", "To (µs)", "Operators"], [[us(a), us(b), c] for a, b, c in h_])

    p("**Finding the stalls: a sweep** (fast path; batch 8 images so the convolutions are worth tiling):\n")
    m8 = trace_export(models.tiny_cnn(), (models.image(8),), model_name="tiny-cnn-b8")
    rows = []
    for buf in (128 * KiB, 512 * KiB, 2 * MiB):
        for bw in (12.8e9, 25.6e9, 102.4e9):
            for arr in (32, 64):
                prog = lower(m8, preset("edge-npu", buffer_bytes=buf, dram_bw=bw, array_rows=arr, array_cols=arr))
                rep = report(prog, fastpath.run(prog))
                rows.append([f"{buf // KiB} KiB", f"{bw / 1e9:,.1f}", f"{arr}x{arr}", prog.n_tiles, us(rep.makespan),
                             *stall_cols(rep), rep.hotspot])
    table(["Buffer", "DRAM GB/s", "Array", "Tiles", "Latency (µs)", "Computing", "Load bandwidth", "Buffer full",
           "Dependency", "Hot-spot"], rows)

    # ── 4. Real model ───────────────────────────────────────────────────
    h("4. A real model configuration: GPT-2 and Llama-3-8B prefill (meta device, no weights)")
    rows = []
    real = {}
    for name, route, tok, pre in (("gpt2", "export", 128, "edge-npu"), ("gpt2", "export", 128, "dc-npu"),
                                  ("llama3-8b", "dispatch", 2048, "dc-npu")):
        tr = capture_registry(name, route, tok, None)
        prog = lower(tr, preset(pre))
        tm = fastpath.run(prog)
        rep = report(prog, tm)
        real[(name, pre)] = (tr, prog, tm, rep)
        rows.append([name, route, tok, pre, len(tr.ops), f"{prog.n_tiles:,}", ms(rep.makespan),
                     f"{2 * sum(t.macs for t in prog.tiles) / rep.makespan / 1e12:,.2f}",
                     pct(rep.components["compute array"]["busy"]), pct(rep.components["off-chip memory"]["bw_util"]),
                     f"{rep.traffic['tiled_bytes'] / rep.traffic['op_bytes']:.2f}", rep.hotspot])
    table(["Model", "Route", "Tokens", "Preset", "Operators", "Tiles", "Latency (ms)", "Array TFLOP/s achieved",
           "Array busy", "DRAM bandwidth used", "Traffic / operator bytes", "Hot-spot"], rows)
    tr, prog, tm, rep = real[("gpt2", "edge-npu")]
    p("GPT-2, 128-token prefill on `edge-npu`:\n")
    p(rep.to_markdown(6))
    p()
    timeline_png(prog, tm, rep, IMG / "timeline_gpt2.png", title="GPT-2 prefill (128 tokens) on edge-npu")
    p("![GPT-2 timeline](../docs/img/timeline_gpt2.png)")

    # ── 5. Cycle-stepped vs event-driven ───────────────────────────────
    h("5. Process-based (event-driven) against cycle-based (cycle-stepped)")
    p("The same quantised program (every duration rounded up to whole cycles at 1 GHz) on both engines. "
      "`Identical` compares every tile's eight event times.")
    rows = []
    small = [("tiny-cnn", ex)]
    tl = models.build(models.tiny_llama(), device="cpu", dtype=torch.float32)
    small.append(("tiny-llama, 32 tokens", trace_export(tl, (models.tokens(1, 32, "cpu"),), {"use_cache": False})))
    small.append(("gpt2, 128 tokens", real[("gpt2", "edge-npu")][0]))
    for label, tr in small:
        prog = lower(tr, preset("edge-npu", quantise=True))
        (ev, st), t_ev = best(lambda prog=prog: simulate(prog), 3)
        (cy, cs), t_cy = best(lambda prog=prog: simulate_cycles(prog, max_cycles=10**9), 1)
        rows.append([label, prog.n_tiles, f"{cs.cycles:,}", f"{st.events:,}", f"{cs.evaluations:,}",
                     f"{t_ev:.3f}", f"{t_cy:.2f}", f"{t_cy / t_ev:,.0f}x",
                     "yes" if ev.as_tuple() == cy.as_tuple() else "NO"])
    table(["Program", "Tiles", "Cycles", "SimPy events", "Cycle-model evaluations", "SimPy (s)", "Cycle-stepped (s)",
           "Slower by", "Identical"], rows)

    # ── 6. NTT ──────────────────────────────────────────────────────────
    h("6. An FHE-style workload: polynomial products through the NTT")
    p("One RNS polynomial product, N = 2^16, 24 limbs (per limb: NTT a, NTT b, pointwise multiply, INTT; "
      "8-byte words). An NTT is (N/2)·log2 N butterflies at 3 operations each, which is 3·log2 N / 16 = "
      "3.0 operations per input byte at N = 2^16. *In transit* puts the NTT in a stage in the memory read path "
      "with the given budget in operations per byte (**speculative**; the budgets are illustrative). "
      "*Vector lanes* sets how fast the on-chip NTT is.")
    rows = []
    tr = polymul_trace(16, 24)
    for pre in ("edge-npu", "dc-npu"):
        for lanes in ((64, 8) if pre == "edge-npu" else (512, 16)):
            base = None
            for budget in (None, 0.5, 1.6, 3.0, 6.0):
                cfg = preset(pre, vector_lanes=lanes, transit_ops_per_byte=budget)
                prog = lower(tr, cfg)
                rep = report(prog, fastpath.run(prog))
                base = base or rep.makespan
                rows.append([pre, lanes, "on chip" if budget is None else f"in transit, {budget}", us(rep.makespan),
                             f"{base / rep.makespan:.2f}x", pct(rep.components["vector unit"]["busy"]),
                             rep.hotspot])
    table(["Preset", "Vector lanes", "NTT runs", "Latency (µs)", "Speed-up", "Vector unit busy", "Hot-spot"], rows)
    prog = lower(tr, preset("dc-npu", vector_lanes=16))
    tm = fastpath.run(prog)
    timeline_png(prog, tm, report(prog, tm), IMG / "timeline_polymul.png",
                 title="Polynomial product, N=2^16 x 24 limbs, dc-npu with 16 vector lanes")
    p("![Polynomial-product timeline, NTTs on a 16-lane vector unit](../docs/img/timeline_polymul.png)")

    # ── 7. Fast path ────────────────────────────────────────────────────
    h("7. The hot path in C++: SimPy, the Python recurrence and the pybind11 module")
    p("Wall-clock seconds, best of 3 (SimPy: best of 2 for the largest program). *C++ kernel* is `Pipeline.run()` "
      "alone; *C++ call* adds building the columns in Python and converting them (what `fastpath.run` costs). "
      "*Lowering* (trace to tiles, Python) is shown because it bounds the end-to-end gain. Every engine's timings "
      "were checked identical to SimPy's.")
    progs = [("tiny-cnn (edge-npu)", lower(ex, preset("edge-npu"))),
             ("gpt2 128 (edge-npu)", real[("gpt2", "edge-npu")][1]),
             ("llama3-8b 2048 (dc-npu)", real[("llama3-8b", "dc-npu")][1])]
    l8 = capture_registry("llama3-8b", "dispatch", 512, None)
    progs.append(("llama3-8b 512 (edge-npu)", lower(l8, preset("edge-npu"))))
    rows = []
    from simfront.accel import _fastpath

    for label, prog in progs:
        big = prog.n_tiles > 50_000
        (sp, _), t_sp = best(lambda prog=prog: simulate(prog), 2 if big else 3)
        py, t_py = best(lambda prog=prog: fastpath.run_py(prog))
        cc, t_cc = best(lambda prog=prog: fastpath.run_cpp(prog))
        a = prog.arrays()
        pipe = _fastpath.Pipeline(a["op"], a["first"], a["last"], a["stores"], a["alloc_in"], a["alloc_out"],
                                  a["load_dur"], a["comp_dur"], a["store_dur"], a["deps"], a["n_ops"],
                                  a["capacity"])
        _, t_k = best(pipe.run, 5)
        same = sp.as_tuple() == py.as_tuple() == cc.as_tuple()
        rows.append([label, f"{prog.n_tiles:,}", f"{t_sp:.3f}", f"{t_py:.4f}", f"{t_cc:.4f}", f"{t_k:.5f}",
                     f"{t_sp / t_py:,.0f}x", f"{t_py / t_cc:,.1f}x", f"{t_py / t_k:,.0f}x", "yes" if same else "NO"])
    table(["Program", "Tiles", "SimPy (s)", "Python recurrence (s)", "C++ call (s)", "C++ kernel (s)",
           "Recurrence vs SimPy", "C++ call vs Python", "C++ kernel vs Python", "Identical"], rows)
    lo_rows = []
    for label, tr, pre in (("gpt2 128 (edge-npu)", real[("gpt2", "edge-npu")][0], "edge-npu"),
                           ("llama3-8b 2048 (dc-npu)", real[("llama3-8b", "dc-npu")][0], "dc-npu"),
                           ("llama3-8b 512 (edge-npu)", l8, "edge-npu")):
        _, t_lo = best(lambda tr=tr, pre=pre: lower(tr, preset(pre)), 3)
        lo_rows.append([label, f"{t_lo:.4f}"])
    table(["Program", "Lowering, Python (s)"], lo_rows)

    # ── 8. EP partitioning ──────────────────────────────────────────────
    h("8. Execution providers: what ONNX Runtime ran, and a simulated device's share")
    import numpy as np

    rows_ort = ep.ort_providers(onnx_path, {onnx_ins[0]: np.zeros((1, 3, 32, 32), dtype=np.float32)})
    by = {}
    for r in rows_ort:
        by.setdefault(r["provider"], []).append(r["op_type"])
    p("ONNX Runtime, the tiny CNN with weights, graph optimisations off, profiling on. Nodes per provider, read "
      "from the profile:\n")
    table(["Provider", "Nodes", "Operator types"],
          [[k, len(v), ", ".join(sorted(set(v)))] for k, v in by.items()])
    p("The same graph partitioned by `simfront.accel.ep.claim` for a device that supports the listed operator "
      "types, and costed with `ep.simulate` (device: `edge-npu`; host: the illustrative host CPU roofline; link "
      "64 GB/s, 1 µs per transfer):\n")
    rows = []
    for label, ops_, cats in (("Conv, Gemm", {"Conv", "Gemm"}, {"matmul"}),
                              ("+ Relu, MaxPool", {"Conv", "Gemm", "Relu", "MaxPool"},
                               {"matmul", "elementwise", "reduction"}),
                              ("+ BatchNormalization, ReduceMean (everything)",
                               {"Conv", "Gemm", "Relu", "MaxPool", "BatchNormalization", "ReduceMean"},
                               {"matmul", "elementwise", "reduction", "norm"})):
        part = ep.claim(onnx_path, ops_ | {"Reshape", "Constant"} if "everything" in label else ops_)
        cost, _ = ep.simulate(on, cats, preset("edge-npu"))
        rows.append([label, f"{part.claimed}/{len(part.nodes)}", len(part.subgraphs), cost.crossings,
                     f"{cost.crossing_bytes / 1e3:,.1f}", us(cost.device_s), us(cost.host_s), us(cost.link_s),
                     us(cost.total)])
    table(["Device supports", "Nodes claimed", "Subgraphs", "Crossings", "Crossing kB", "Device (µs)", "Host (µs)",
           "Link (µs)", "Total (µs)"], rows)

    (HERE / "accel_results.md").write_text("\n".join(OUT) + "\n")
    print("\n".join(OUT))


def _fifo_plot(runs):
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig, axes = plt.subplots(2, 1, figsize=(10, 5.2), sharex=True)
    for ax, label in zip(axes, ("slow consumer", "bursty"), strict=True):
        for depth, colour in ((2, "#c0504d"), (16, "#3b6ea8")):
            r = runs[(label, depth)]
            pts = [(t, d) for t, d in r.trace if t <= 120]
            ax.step([t for t, _ in pts], [d for _, d in pts], where="post", color=colour, linewidth=1.1,
                    label=f"depth {depth}")
        ax.set_ylabel("items in FIFO")
        ax.set_title(f"{label}: producer blocked {runs[(label, 2)].producer_blocked / runs[(label, 2)].end:.0%} "
                     f"(depth 2), {runs[(label, 16)].producer_blocked / runs[(label, 16)].end:.0%} (depth 16)",
                     fontsize=10)
        ax.legend(loc="upper left", fontsize=8, facecolor="white", framealpha=1)
        ax.grid(alpha=0.3)
    axes[-1].set_xlabel("time (units)")
    fig.tight_layout()
    fig.savefig(IMG / "fifo_depth.png", dpi=110)
    plt.close(fig)


if __name__ == "__main__":
    main()
